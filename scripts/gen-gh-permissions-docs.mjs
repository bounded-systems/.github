#!/usr/bin/env node
// Generate scripts/gh-permissions-docs.json from GitHub's own page.
//
// This file used to be transcribed by hand, which made every count derived
// from it an assertion. It is now PARSED, so the numbers are reproducible and
// the parse is what can be argued with. The first run caught a transcription
// error (13 account permissions recorded, 14 published).
//
// The page's structure is load-bearing and stable enough to depend on:
//
//   <h2|h3 id="{plane}-permissions-for-{slugified-name}">
//     {Plane} permissions for "{Display Name}"
//   ...followed by a table of  VERB /path  <access>  <token types>
//
// The access column is the grant vocabulary's level set, and the endpoint
// column is an endpoint->permission mapping that is NOT in the OpenAPI
// description (0 of 1220 operations carry it). It is published only here, as
// HTML. Anything the parse cannot classify throws rather than dropping out of
// the enumeration -- a permission silently missing from a generated file is
// exactly the invisibility this repo keeps paying for (see I1).
//
//   node scripts/gen-gh-permissions-docs.mjs           rewrite the JSON
//   node scripts/gen-gh-permissions-docs.mjs --check    exit 1 if stale
//   node scripts/gen-gh-permissions-docs.mjs --stdout   print, don't write

import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(root, "scripts", "gh-permissions-docs.json");
const SRC = "https://docs.github.com/en/rest/authentication/permissions-required-for-github-apps";

const PLANES = ["enterprise", "organization", "repository", "user"];
const LEVELS = ["read", "write", "admin"];
const HEADING = new RegExp(
  `<h[23][^>]*id="((?:${PLANES.join("|")})-permissions-for-[^"]+)"`,
  "g",
);
const ENDPOINT = /\b(GET|POST|PUT|PATCH|DELETE)\s+(\/\S*)\s+(read|write|admin)\b/g;

// One pass, not a chain of replaces. Unescaping `&amp;` in its own pass feeds
// the resulting `&` back into the later passes, so `&amp;lt;` -- the escaped
// form of the literal text `&lt;` -- would come out as `<`. Replacing every
// entity in a single scan means no output is ever re-scanned.
const ENTITIES = {
  "&quot;": '"',
  "&#x27;": "'",
  "&apos;": "'",
  "&amp;": "&",
  "&lt;": "<",
  "&gt;": ">",
  "&nbsp;": " ",
};
export const unescape = (s) =>
  s.replace(/&(?:quot|#x27|apos|amp|lt|gt|nbsp);/g, (e) => ENTITIES[e]);

const strip = (s) => unescape(s.replace(/<[^>]+>/g, " ").replace(/\s+/g, " ")).trim();

export function parse(html) {
  const heads = [...html.matchAll(HEADING)].map((m) => ({ anchor: m[1], at: m.index }));
  if (heads.length === 0) throw new Error("no permission headings found -- page structure changed");

  const permissions = heads.map((h, i) => {
    const seg = html.slice(h.at, i + 1 < heads.length ? heads[i + 1].at : html.length);
    const text = strip(seg);
    const plane = h.anchor.split("-permissions-for-")[0];

    const named = text.match(/permissions for ["“]([^"”]+)["”]/i);
    if (!named) throw new Error(`${h.anchor}: cannot read display name from heading`);

    const endpoints = [...text.matchAll(ENDPOINT)].map(([, verb, path, access]) => ({
      endpoint: `${verb} ${path}`,
      access,
    }));
    if (endpoints.length === 0) {
      // Not tolerated: a permission with no table is either a page change or a
      // parse failure, and both must be looked at rather than silently yielding
      // a permission with no levels.
      throw new Error(`${h.anchor}: no endpoint rows parsed`);
    }

    const levels = LEVELS.filter((l) => endpoints.some((e) => e.access === l));
    return { plane, name: named[1], anchor: h.anchor, levels, endpoints: endpoints.length };
  });

  const seen = new Set();
  for (const p of permissions) {
    const key = `${p.plane}/${p.name}`;
    if (seen.has(key)) throw new Error(`duplicate permission ${key}`);
    seen.add(key);
  }
  return permissions;
}

const byPlane = (perms) =>
  Object.fromEntries(PLANES.map((p) => [p, perms.filter((x) => x.plane === p).length]));

if (import.meta.url === `file://${process.argv[1]}`) {
  const args = new Set(process.argv.slice(2));
  const res = await fetch(SRC, { headers: { "User-Agent": "bounded-systems-ocap-github" } });
  if (!res.ok) throw new Error(`${res.status} fetching ${SRC}`);
  const html = await res.text();
  const permissions = parse(html);

  const doc = {
    $comment:
      "GENERATED by scripts/gen-gh-permissions-docs.mjs from the source page. Do not edit by hand. " +
      "`levels` is the set of access levels appearing in that permission's endpoint table; " +
      "`endpoints` is how many rows that set was derived from. `plane` is the page's own " +
      "grouping and is the ONLY place plane information exists -- it is not recoverable from " +
      "the wire slug (see `members`).",
    source: SRC,
    source_sha256: createHash("sha256").update(html).digest("hex"),
    retrieved: new Date().toISOString().slice(0, 10),
    counts: { total: permissions.length, ...byPlane(permissions) },
    permissions,
  };
  const json = `${JSON.stringify(doc, null, 2)}\n`;

  if (args.has("--stdout")) {
    console.log(json);
  } else if (args.has("--check")) {
    // Compare everything except the volatile fields: the page's byte digest and
    // the retrieval date change on every edit GitHub makes, including ones that
    // touch no permission. Drift that matters is drift in the permissions.
    const current = JSON.parse(await readFile(OUT, "utf8"));
    const same = JSON.stringify(current.permissions) === JSON.stringify(permissions);
    console.log(
      `${permissions.length} permissions (${Object.entries(byPlane(permissions))
        .map(([k, v]) => `${k} ${v}`)
        .join(", ")})`,
    );
    if (!same) {
      console.error("gh-permissions-docs.json is stale; re-run without --check");
      process.exit(1);
    }
    console.log("gh-permissions-docs.json: in sync with the source page");
  } else {
    await writeFile(OUT, json);
    console.log(`wrote ${OUT}: ${permissions.length} permissions`);
  }
}
